// Stroke data for all 46 basic hiragana
// Each stroke is an array of [x, y] control points (0-1 normalized coordinates)
// These represent the path the user should follow

export interface HiraganaChar {
  char: string
  romaji: string
  strokeCount: number
  strokes: number[][][]  // strokes[strokeIndex] = array of [x, y] points
}

export interface GojuonRow {
  label: string
  chars: (HiraganaChar | null)[]
}

